def pages(buffer: bytes, offset: int, size: int) -> Iterable[bytes]:
    """generate pages of buffer with size bytes starting at offset"""
    yield from (
        buffer[start:end]
        for start, end in pairwise(range(offset, len(buffer) + 1, size))
    )


class DataclassInstance(Protocol):
    """
    Protocol for type checkers to identify classes that are generated by
    @dataclass.
    """

    __dataclass_fields__: ClassVar[dict[str, Field[Any]]]


class classproperty[T]:
    # Use an ellipsis to bypass the instance vs class argument conflict
    def __init__(self, func: Callable[..., T]) -> None:
        self.fget = func

    # Scope the class parameter 'C' strictly to the __get__ method
    def __get__[C](self, instance: object, owner: type[C]) -> T:
        return self.fget(owner)


class Metrics(DataclassInstance):
    """Base class to pack() and unpack() dataclasses."""

    struct: ClassVar[Struct]

    @classmethod
    def unpack(cls, buffer: bytes) -> Self:
        return cls(*cls.struct.unpack(buffer))

    def _value_to_pack(self, obj: Any) -> Any:
        """
        Get the value to emit for the value of one of self's fields.
        list() values result in zero bytes to allow sublcasses to put a zero
        byte field in their format string and rely on this to provide the
        value and only have to override pack().
        """
        match obj:
            case Metrics():
                return obj.pack()
            case Enum():
                return obj.value
            case list():
                return b""
            case _:
                return obj

    def field_values(self) -> Iterable[tuple[str, Any]]:
        """
        Get the field values that will be packed.

        Subclasses can override this to inject fields that aren't user settable
        and aren't in the dataclass fields. For example, Message uses this to
        insert the automatically managed message_type.
        """
        yield from ((field.name, getattr(self, field.name)) for field in fields(self))

    def pack(self) -> bytes:
        """
        Return the byte packed representation.
        Sublcases should override this as needed to replace placeholder (zero
        byte) in the struct format with the proper bytes.
        """
        pack_values = (self._value_to_pack(value) for _, value in self.field_values())
        return self.struct.pack(*pack_values)

    @classproperty
    def format(cls) -> str:
        return f"{cls.struct.size}s"


class StateEnum(Enum):
    ERROR = 1 << 0
    IDLE = 1 << 1
    RUNNING = 1 << 2
    PAUSED = 1 << 3
    COMPLETE = 1 << 4
    THERMOCOUPLE_ERROR = 1 << 5
    OVER_TEMP = 1 << 6
    HEATING_FAILED = 1 << 7
    REGULATION_FAILURE = 1 << 8
    COMMUNICATION_ERROR = 1 << 9
    DOOR_OPEN = 1 << 10

    def __or__(self, other: int | StateEnum) -> int:
        return self.value | (other.value if isinstance(other, StateEnum) else other)


@dataclass
class State(Metrics):
    struct: ClassVar[Struct] = Struct("<H")
    state: StateEnum

    def __post_init__(self) -> None:
        self.state = StateEnum(self.state)


class MessageType(Enum):
    START = 1
    PAUSE = 2
    RESUME = 3
    STOP = 4
    SET_TIME = 5
    SAMPLE_ACK = 6
    TELEMETRY = 7

    @classmethod
    def unpack(cls, buffer: bytes) -> Message:
        """unpack a command which has a type that is not known ahead of time"""
        message_type = MessageType(
            Message.struct.unpack(buffer[: Message.struct.size])[0]
        )
        match message_type:
            case MessageType.START:
                return StartCommand.unpack(buffer)
            case MessageType.PAUSE:
                return PauseCommand.unpack(buffer)
            case MessageType.RESUME:
                return ResumeCommand.unpack(buffer)
            case MessageType.STOP:
                return StopCommand.unpack(buffer)
            case MessageType.SET_TIME:
                return SetTimeCommand.unpack(buffer)
            case MessageType.SAMPLE_ACK:
                return SampleAckMessage.unpack(buffer)
            case MessageType.TELEMETRY:
                return Telemetry.unpack(buffer)
            case _:
                raise ValueError(f"command type {message_type} is unknown {buffer=}")


@dataclass
class Temperature(Metrics):
    struct: ClassVar[Struct] = Struct("<hhhh")
    current: int  # int16_t
    target: int  # int16_t
    cold_junction: int  # int16_t
    core: int  # int16_t


@dataclass
class Memory(Metrics):
    struct: ClassVar[Struct] = Struct("<IIIII")
    size: int  # uint32_t
    heap_free: int  # uint32_t
    min_heap_free: int  # uint32_t
    largest_allocatable: int  # uint32_t
    sample_buffer_size: int  # uint32_t


@dataclass
class Sample(Metrics):
    struct: ClassVar[Struct] = Struct(f"<IBH{Temperature.format}B{Memory.format}")
    timestamp: int  # uint32_t
    sub_sample_count: int  # uint8_t
    state: int  # uint16_t
    temperature: Temperature
    duty_cycle: int  # uint8_t
    memory: Memory

    def __post_init__(self) -> None:
        if isinstance(self.memory, bytes):
            self.memory = Memory.unpack(self.memory)
        if isinstance(self.temperature, bytes):
            self.temperature = Temperature.unpack(self.temperature)


@dataclass
class Message(Metrics, ABC):
    struct: ClassVar[Struct] = Struct("<B")
    message_type: ClassVar[MessageType]

    @override
    def field_values(self) -> Iterable[tuple[str, Any]]:
        # insert command type into fields to pack
        yield from (("message_type", self.message_type), *super().field_values())

    @override
    @classmethod
    def unpack(cls, buffer: bytes) -> Self:
        args = cls.struct.unpack(buffer)
        if args[0] != cls.message_type.value:
            raise ValueError(
                f"received {MessageType(args[0])} when expecting {cls.message_type}"
            )
        return cls(*args[1:])


@dataclass
class Command(Message): ...


@dataclass
class ClientMessage(Message): ...


@dataclass
class Telemetry(ClientMessage):
    struct: ClassVar[Struct] = Struct(f"{Message.struct.format}QI{State.format}H0s")
    message_type = MessageType.TELEMETRY

    timestamp_ms: int
    uptime: int
    state: State
    sample_count: int
    samples: list[Sample]

    def __post_init__(self) -> None:
        if isinstance(self.state, bytes):
            self.state = State.unpack(self.state)

    @override
    @classmethod
    def unpack(cls, buffer: bytes) -> Self:
        self = super().unpack(buffer[: cls.struct.size])
        self.samples = [
            Sample.unpack(_buffer)
            for _buffer in pages(buffer, self.struct.size, Sample.struct.size)
        ]
        return self

    @override
    def pack(self) -> bytes:
        return b"".join((super().pack(), *(sample.pack() for sample in self.samples)))


@dataclass
class SetTimeCommand(Command):
    struct: ClassVar[Struct] = Struct(Message.struct.format + "Q")
    message_type: ClassVar[MessageType] = field(
        default=MessageType.SET_TIME, init=False
    )
    timestamp: int = field(default_factory=lambda: int(time.time() * 1000))


