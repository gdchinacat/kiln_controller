@contextmanager
def assert_http_status_error(
    code: int,
    detail_type: str | None = None,
) -> Generator[pytest.ExceptionInfo[httpx2.HTTPStatusError]]:
    """
    Assert the managed block raises httpx2.HTTPStatusError.
    The exception is the context manager value so the response can be validated
    as well:
        with assert_http_status_error(httpx2.codes.UNPROCESSABLE_CONTENT) as hse:
            user.delete()
        assert hse.value.response.json()["detail"][0]["type"] == "USER_HAS_SCHEDULES"
    """
    with pytest.raises(httpx2.HTTPStatusError) as hse:
        yield hse
    assert hse.value.response.status_code == code
    if detail_type:
        assert hse.value.response.json()["detail"][0]["type"] == detail_type


@kwargs.factory
def user_fixture(
    *,
    admin_client: Client,
    name: str = "name",
    username: str | None = None,
    password: str | None = "password",
    skip_create: bool = False,
    skip_delete: bool = False,
    _user_count: Iterator[int] = count(),
    **kwargs: dict[str, Any],
) -> Generator[User]:
    """
    Create a user.

    If username is not specified one is autogenerated to (hopefully) avoid
    conflict with existing user when running with LIVE_SERVICE=true. No attempt
    is made to actually ensure it doesn't conflict (it's random).

    skip_create causes the user to not be inserted (useful for when you need
    a user with a uniqueish username that hasn't been created on the server).
    """
    username = username or f"username{next(_user_count)}"
    user = User(name=name, username=username, password=password)
    if not skip_create:
        user.post(admin_client)
    yield user
    if not skip_delete:
        user.delete()


@kwargs.factory
def user_client(
    *,
    service: Service,
    user: User,
    **_: object,
) -> Generator[Client]:
    """Get a client using users authorization."""
    assert user.password is not None
    with httpx2.Client(
        base_url=user._client._http_client.base_url,
        verify=service.client_ssl_context,
    ) as http_client:
        client = Client(http_client)
        client.login(user.username, user.password)

        # Update the user to use its own client.
        parent = user._parent
        user._parent = client
        try:
            yield client
        finally:
            # user_client is created from a user so when the fixtures unwind
            # during cleanup this client is closed before the user is deleted
            # so restore the original client so the user.delete can succeed.
            user._parent = parent
            http_client.close()


